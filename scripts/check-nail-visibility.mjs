import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {importTypescript} from './lib/import-typescript.mjs';
const {estimateHandPose}=await importTypescript('src/lib/handPose.ts');
const {assessNailVisibility,NailVisibilityTracker,withNailVisibility}=await importTypescript('src/lib/nailVisibility.ts');
const {traceNailContour,traceNailRegion}=await importTypescript('src/lib/nailContour.ts');
const {NailTrackStabilizer}=await importTypescript('src/lib/trackingQuality.ts');
const {buildNailsFromLandmarks}=await importTypescript('src/lib/nailGeometry.ts');
const fixture=JSON.parse(await readFile('scripts/fixtures/thumb-fit-geometry.json','utf8'));
const landmarks=fixture.landmarks.map(p=>({...p,z:0}));
const identity={categoryName:'Right',score:.99};
const back=estimateHandPose(landmarks,undefined,identity,fixture.aspect);
assert.equal(back.view,'back');
const palm=estimateHandPose(landmarks,undefined,{...identity,categoryName:'Left'},fixture.aspect);
assert.equal(palm.view,'palm');
const reflected=landmarks.map(p=>({...p,x:1-p.x}));
assert.equal(estimateHandPose(reflected,undefined,{...identity,categoryName:'Left'},fixture.aspect).view,'back','raw reflection with changed model label changed the surface');
assert.equal(estimateHandPose(landmarks,undefined,{...identity,score:.5},1).view,'unknown');
assert.equal(estimateHandPose(landmarks,undefined,undefined,1).view,'unknown');
assert.equal(estimateHandPose(landmarks.map(()=>({x:.5,y:.5,z:0})),undefined,identity,1).view,'unknown');
assert.equal(estimateHandPose(landmarks,reflected,identity,fixture.aspect).view,'unknown','world/image disagreement was trusted');
const sidePoints=landmarks.map(p=>({x:(p.x-.5)*.05+.5,y:p.y,z:(p.x-.5)}));
assert.equal(estimateHandPose(sidePoints,undefined,identity,fixture.aspect).view,'side');

const nails=buildNailsFromLandmarks(landmarks,false,fixture.aspect);
const blank=nails.map(()=>({accepted:false,confidence:0,reason:'test'}));
const get=(pose=back,fit=blank,ns=nails,lm=landmarks,mirrored=false,w=1280,h=720)=>assessNailVisibility(pose,lm,ns,fit,w,h,mirrored);
assert.ok(get().every(e=>e.state==='visible'),'flat back should use the safe dorsal prior');
assert.ok(get(palm).every(e=>e.hardHidden),'open palm must not paint pads');
assert.deepEqual(get(back,blank,buildNailsFromLandmarks(landmarks,true,fixture.aspect),landmarks,true).map(e=>e.state),get().map(e=>e.state),'display mirror changed visibility');
assert.ok(get(back,blank,nails,landmarks,false,20,12).every(e=>e.hardHidden),'subpixel nails accepted');
const contour=[{x:40,y:40},{x:50,y:40},{x:50,y:50},{x:40,y:50}];
const supported=nails.map(()=>({accepted:true,confidence:.94,reason:'test',contour,supportThresholds:3}));
assert.ok(get(palm,supported).every(e=>e.hardHidden),'colour alone made an open palm visible');
const curled={...palm,fingers:palm.fingers.map(f=>({...f,facing:.7,bendDegrees:115,outOfPlaneDegrees:80}))};
assert.ok(get(curled,supported).every(e=>e.state==='partial'&&e.contour===contour),'curled visible nails need a current bounded contour');
assert.ok(get(curled).every(e=>e.hardHidden),'curled pose alone invented a visible nail');
assert.ok(get({...back,view:'side'},supported).every(e=>e.state==='partial'));
assert.ok(get({...back,view:'side'}).every(e=>e.hardHidden));
const thumbRoll={...curled,fingers:curled.fingers.map(f=>({...f,facing:-.6}))};
assert.equal(get(thumbRoll,supported)[0].state,'partial','strong thumb boundary could not resolve curl/roll ambiguity');
assert.ok(get(thumbRoll,supported).slice(1).every(e=>e.hardHidden),'thumb-only exception affected other fingers');
const weak=supported.map(f=>({...f,confidence:.85}));
assert.equal(get(thumbRoll,weak)[0].hardHidden,true,'weak thumb colour override was trusted');
const spreadPalm={...thumbRoll,fingers:thumbRoll.fingers.map(f=>({...f,outOfPlaneDegrees:0}))};
assert.equal(get(spreadPalm,supported)[0].hardHidden,true,'in-plane thumb spread was mistaken for palm-side nail curl');
// A nearer finger capsule must occlude a more distant nail proposal.
const crossed=landmarks.map(p=>({...p}));
const angle=(nails[1].rotation-90)*Math.PI/180;
const center={x:nails[1].x/100+Math.cos(angle)*nails[1].height/200/fixture.aspect,y:nails[1].y/100+Math.sin(angle)*nails[1].height/200};
crossed[10]={...center,z:-.1};crossed[11]={...center,y:center.y-.02,z:-.1};crossed[12]={...center,y:center.y-.04,z:-.1};
assert.equal(get(back,blank,nails,crossed)[1].reason,'overlapping-closer-finger');

const tracker=new NailVisibilityTracker();
const visible=get(),hidden=get(palm);
for(let t=0;t<=300;t+=50)tracker.update(visible,t,'Right');
assert.ok(tracker.update(visible,350,'Right').every(v=>v.alpha===1));
assert.ok(tracker.update(hidden,400,'Right').every(v=>v.alpha===0),'palm fade painted the finger pads');
let recoveredAt;
for(let t=450;t<=750;t+=50){const result=tracker.update(visible,t,'Right');if(recoveredAt===undefined&&result.some(v=>v.alpha>0))recoveredAt=t;}
assert.equal(recoveredAt-450,100,'synthetic recovery did not respect the 70ms entry hold');
assert.ok(tracker.update(visible,700,'Right').every(v=>v.alpha===0),'old result repainted a newer frame');
assert.ok(tracker.update(visible,800,'Left').every(v=>v.alpha===0),'hand identity swap kept old alpha');
const transient=new NailVisibilityTracker();
assert.ok(transient.update(visible,0,'Right').every(v=>v.alpha===0));
assert.ok(transient.update(hidden,50,'Right').every(v=>v.alpha===0),'single-frame candidate flashed');
assert.ok(withNailVisibility(nails,[]).every(n=>n.visibility===0));
const partial=withNailVisibility(nails,get(curled,supported));
assert.ok(partial.every(n=>n.clipContour===contour&&n.visibility===1));
const stabilizer=new NailTrackStabilizer();
stabilizer.update(nails,0);
const moved=nails.map((n,i)=>({...n,x:n.x+(i===0?20:1)}));
stabilizer.resetFingers([0]);
const reset=stabilizer.update(moved,50);
assert.equal(reset[0].x,moved[0].x,'reappearing finger used stale position/outlier gate');
assert.ok(reset[1].x<nails[1].x+1,'resetting thumb disabled another finger filter');

const shape=(rows)=>traceNailContour(Uint8Array.from(rows.join('').split('').map(Number)),rows[0].length,rows.length,(x,y)=>({x,y}));
assert.equal(shape(['111','100','100']).length,6,'concavity was replaced by a convex hull');
assert.equal(shape(['111','101','111']),undefined,'hole contour was bridged');
assert.equal(shape(['100','000','001']),undefined,'disconnected regions were bridged');
assert.equal(shape(['10','01']),undefined,'touching branches were bridged');
assert.equal(shape(['000','000']),undefined);
const hole=traceNailRegion(Uint8Array.from([1,1,1,1,0,1,1,1,1]),3,3,(x,y)=>({x,y}));
assert.equal(hole.holes.length,1,'internal gaps were not preserved');
assert.equal(hole.contour.length,4);assert.equal(hole.holes[0].length,4);

// Exercise the actual renderer: hidden fingers never reach nail painting,
// partial alpha/clip apply to material and shadow and remain balanced for saving.
const {drawNails}=await importTypescript('src/lib/nailRenderer.ts');
const {defaultDesign}=await importTypescript('src/lib/defaults.ts');
let depth=0;const log=[];const state={globalAlpha:1};const stack=[];
const ctx=new Proxy(state,{get(target,key){if(key in target)return target[key];
 if(key==='save')return()=>{stack.push({...target});depth++;};
 if(key==='restore')return()=>{Object.assign(target,stack.pop());depth--;};
 if(String(key).startsWith('create'))return()=>({addColorStop(){}});
 return(...args)=>log.push({key,args,alpha:target.globalAlpha});}});
await drawNails(ctx,640,480,withNailVisibility(nails,hidden),defaultDesign);
assert.equal(log.filter(v=>v.key==='fill'||v.key==='fillRect').length,0);
log.length=0;
await drawNails(ctx,640,480,[{...partial[0],visibility:.4,clipHoles:[contour]}],defaultDesign,{opacity:.5});
const clips=log.flatMap((v,i)=>v.key==='clip'?[i]:[]),translations=log.flatMap((v,i)=>v.key==='translate'?[i]:[]);
assert.ok(clips[1]<translations[1],'fragment clip applied after nail painting/transforms');
assert.deepEqual(log[clips[1]].args,['evenodd'],'holes were filled rather than clipped');
assert.ok(log.filter(v=>v.key==='fillRect'||v.key==='fill').every(v=>v.alpha<=.2),'material or shadow ignored visibility alpha');
assert.equal(depth,0);assert.equal(ctx.globalAlpha,1);
log.length=0;
await drawNails(ctx,640,480,[{...partial[0],clipContour:undefined}],defaultDesign);
assert.equal(log.filter(v=>v.key==='fill'||v.key==='fillRect').length,0,'partial nail without current contour painted');
console.log('nail-visibility: raw handedness/mirror, world disagreement, back/palm/side/curl, bounded fragments, thumb roll, distance/occlusion, temporal recovery, per-finger reset, contour and renderer safety passed (synthetic, not hardware accuracy)');
